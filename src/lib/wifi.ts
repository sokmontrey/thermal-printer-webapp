// WiFi credentials are compile-time today: the sketch reads WIFI_SSID and
// WIFI_PASS from wifi_config.h. This module produces that header and the
// flash commands, so the browser can walk you through provisioning.

export interface WifiForm {
  ssid: string
  password: string
  hostname: string
  staticIp: string
  gateway: string
  subnet: string
}

export const DEFAULT_WIFI: WifiForm = {
  ssid: "",
  password: "",
  hostname: "thermalprint",
  staticIp: "",
  gateway: "",
  subnet: "255.255.255.0",
}

const cEscape = (value: string) =>
  value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')

export function wifiHeader(form: WifiForm): string {
  const lines = [
    "// Generated by the thermal printer web app.",
    "// Copy to sketch/printer_wifi/wifi_config.h and reflash.",
    "#pragma once",
    "",
    `#define WIFI_SSID "${cEscape(form.ssid)}"`,
    `#define WIFI_PASS "${cEscape(form.password)}"`,
  ]
  if (form.staticIp.trim()) {
    lines.push(
      "",
      "// Static addressing, applied in printer_wifi.ino after WiFi.begin().",
      `#define WIFI_IP "${form.staticIp.trim()}"`,
      `#define WIFI_GATEWAY "${form.gateway.trim()}"`,
      `#define WIFI_SUBNET "${form.subnet.trim() || "255.255.255.0"}"`,
    )
  }
  return lines.join("\n") + "\n"
}

export interface CommandStep {
  title: string
  detail: string
  command?: string
}

export function flashSteps(boardPort: string, ssid: string): CommandStep[] {
  const port = boardPort || "/dev/ttyACM0"
  return [
    {
      title: "Write the credentials header",
      detail:
        "Save the generated header as sketch/printer_wifi/wifi_config.h. It is gitignored, so credentials stay out of the repo.",
    },
    {
      title: "Detect the board",
      detail: "Confirm the XIAO shows up over USB before flashing.",
      command: "arduino-cli board list",
    },
    {
      title: "Compile and upload",
      detail: `Flashes the WiFi firmware to ${port}.`,
      command: `arduino-cli compile --fqbn esp32:esp32:XIAO_ESP32C6 -u -p ${port} sketch/printer_wifi`,
    },
    {
      title: "Watch the serial log",
      detail: "The board prints its IP, or falls back to AP mode if the join fails.",
      command: `arduino-cli monitor -p ${port} -c baudrate=115200`,
    },
    {
      title: "Connect to the printer",
      detail: ssid
        ? `After it joins ${ssid}, use thermalprint.local:9100 or the printed IP.`
        : "Enter the network name above, then connect using thermalprint.local:9100.",
    },
  ]
}

